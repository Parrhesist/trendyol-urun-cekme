// Sahne 360 × 260 birim, yaklaşık 10 birim = 1 m. Trafik sağdan akar:
// yatay yolda alt şerit soldan sağa gider, araç alttaki kaldırıma park eder.

/** Yatay iki şeritli sokak: üstte ve altta kaldırım. */
const street = (opts: { to?: number; dashGap?: [number, number] } = {}): SceneEl[] => {
  const to = opts.to ?? 360;
  const dash: SceneEl[] = opts.dashGap
    ? [
        { k: 'dash', x1: 0, y1: 100, x2: opts.dashGap[0], y2: 100 },
        { k: 'dash', x1: opts.dashGap[1], y1: 100, x2: to, y2: 100 },
      ]
    : [{ k: 'dash', x1: 0, y1: 100, x2: to, y2: 100 }];
  return [
    { k: 'walk', x: 0, y: 26, w: to, h: 24 },
    { k: 'road', x: 0, y: 50, w: 360, h: 100 },
    ...dash,
    { k: 'walk', x: 0, y: 150, w: to, h: 26 },
  ];
};

